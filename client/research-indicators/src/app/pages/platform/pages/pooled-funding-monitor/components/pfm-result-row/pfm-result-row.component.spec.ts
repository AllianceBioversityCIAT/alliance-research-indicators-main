import { By } from '@angular/platform-browser';
import { TestBed } from '@angular/core/testing';
import { Tooltip } from 'primeng/tooltip';
import { CustomTagComponent } from '@shared/components/custom-tag/custom-tag.component';
import { provideRouter } from '@angular/router';
import { PfmResultRow } from '../../pfm.interfaces';
import { PfmResultRowComponent } from './pfm-result-row.component';
import { MAPPING_STATUS_COLOR } from '@shared/constants/pfm-status-colors';
import { SYNC_TAG_COLOR } from '@shared/utils/prms-sync-status.util';

const BASE: PfmResultRow = {
  result_code: 'STAR-1234',
  platform_code: 'STAR',
  official_code: 1234,
  report_year: 2025,
  snapshot_years: [],
  title: 'Alpha result',
  type: 'Innovation development',
  creator: 'Ana Perez',
  star_label: 'Submitted',
  star_status_id: 2,
  star_status_name: null,
  star_status_config: null,
  star_status_description: 'Waiting for the PI to sign off',
  star_approved_label: null,
  science_programs: [
    { code: 'SP01', name: 'Breeding', primary: true, color: '#112233' },
    { code: 'SP09', name: 'Climate Action', primary: false, color: null }
  ],
  pi_line: 'Awaiting PI approval',
  mapping_state: 'Pending',
  mapping_note: 'Budget shares missing',
  sp_line: 'SP01 (primary)',
  primary_sp: { code: 'SP01', name: 'Breeding', color: '#112233' },
  contributing: [],
  prms_status: 'Not sent',
  prms_hint: 'Not synced to PRMS yet',
  updated_at: '03 Oct, 14:05'
};

// Real RouterLink with provideRouter([]): the href is generated by Angular, not mocked.
function render(over: Partial<PfmResultRow> = {}) {
  TestBed.resetTestingModule();
  TestBed.configureTestingModule({ imports: [PfmResultRowComponent], providers: [provideRouter([])] });
  const fixture = TestBed.createComponent(PfmResultRowComponent);
  fixture.componentRef.setInput('row', { ...BASE, ...over });
  fixture.detectChanges();
  const el = fixture.nativeElement as HTMLElement;
  const tipOf = (host: HTMLElement) =>
    fixture.debugElement
      .queryAll(By.directive(Tooltip))
      .find(d => host.contains(d.nativeElement))
      ?.injector.get(Tooltip).content;
  const tagsIn = (host: HTMLElement) =>
    fixture.debugElement
      .queryAll(By.directive(CustomTagComponent))
      .filter(d => host.contains(d.nativeElement))
      .map(d => d.componentInstance as CustomTagComponent);
  const sr = (host: HTMLElement) => Array.from(host.querySelectorAll('.sr-only')).map(e => e.textContent?.trim());
  return { el, tipOf, tagsIn, sr, q: (id: string) => el.querySelector(`[data-testid="${id}"]`) as HTMLElement };
}

describe('PfmResultRowComponent', () => {
  it('STAR status renders the Results Center tag (app-custom-tag) with the label, not the PFM badge, and no pi_line text under it (HITL 22)', () => {
    const { q } = render();
    const cell = q('pfm-row-star');
    const tag = cell.querySelector('app-custom-tag');
    expect(tag).not.toBeNull();
    expect(tag?.textContent).toContain('Submitted');
    expect(cell.querySelector('[data-testid="pfm-row-pi-line"]')).toBeNull();
    expect(cell.textContent).not.toContain('Awaiting PI approval');
    expect(cell.querySelector('[data-testid="pfm-row-star-approved"]')).toBeNull();
  });

  it('STAR tag tooltip is the status description, on the icon (HITL 22)', () => {
    const { q, tipOf, sr } = render();
    expect(tipOf(q('pfm-row-star'))).toBe('Waiting for the PI to sign off');
    // The icon is not focusable: the same text is also available to assistive tech.
    expect(sr(q('pfm-row-star'))).toEqual(['Waiting for the PI to sign off']);
  });

  it('STAR cell has no sr-only description when the status has none', () => {
    const { q, sr } = render({ star_status_description: null });
    expect(sr(q('pfm-row-star'))).toEqual([]);
  });

  it('STAR approved date goes into the tag tooltip (and sr-only), never as a line under the tag', () => {
    const { q, tipOf, sr } = render({ star_label: 'Approved', star_status_id: 6, star_approved_label: 'Approved 14 Jul 2026' });
    const cell = q('pfm-row-star');
    expect(tipOf(cell)).toBe('Waiting for the PI to sign off · Approved 14 Jul 2026');
    expect(sr(cell)).toEqual(['Waiting for the PI to sign off · Approved 14 Jul 2026']);
    expect(cell.querySelector('[data-testid="pfm-row-star-approved"]')).toBeNull();
    expect(cell.querySelector('p')).toBeNull();
  });

  it('STAR tooltip is just the approved date when the status has no description', () => {
    const { q, tipOf } = render({ star_status_description: null, star_approved_label: 'Approved 14 Jul 2026' });
    expect(tipOf(q('pfm-row-star'))).toBe('Approved 14 Jul 2026');
  });

  it('STAR tag takes colour, border and icon from star_status_config exactly like the Results Center', () => {
    const { q } = render({
      star_status_config: {
        color: { text: 'rgb(1, 2, 3)', border: 'rgb(4, 5, 6)', background: 'rgb(7, 8, 9)' },
        icon: { name: 'pi-check-circle', color: 'rgb(10, 11, 12)' }
      }
    });
    const tag = q('pfm-row-star').querySelector('app-custom-tag') as HTMLElement;
    const pill = tag.firstElementChild as HTMLElement;
    expect(pill.style.color).toBe('rgb(1, 2, 3)');
    expect(pill.style.borderColor).toBe('rgb(4, 5, 6)');
    const icon = tag.querySelector('i') as HTMLElement;
    expect(icon.classList.contains('pi-check-circle')).toBe(true);
    expect(icon.style.color).toBe('rgb(10, 11, 12)');
  });

  it('STAR tag text is the Results Center status name, not the derived label', () => {
    const { q } = render({ star_status_name: 'Rejected', star_label: 'Returned' });
    expect(q('pfm-row-star').querySelector('app-custom-tag')?.textContent?.trim()).toBe('Rejected');
  });

  it('STAR tag text falls back to star_label when the status name is null', () => {
    const { q } = render({ star_status_name: null, star_label: 'Returned' });
    expect(q('pfm-row-star').querySelector('app-custom-tag')?.textContent?.trim()).toBe('Returned');
  });

  it('STAR tag falls back to the default look when star_status_config is null', () => {
    const { q } = render({ star_status_config: null });
    const icon = q('pfm-row-star').querySelector('app-custom-tag i') as HTMLElement;
    expect(icon.classList.contains('pi-exclamation-circle')).toBe(true);
    const pill = q('pfm-row-star').querySelector('app-custom-tag')?.firstElementChild as HTMLElement;
    // default STATUS_COLOR_MAP[''] look, not an empty colour
    expect(pill.style.borderColor).not.toBe('');
  });

  it('the title links to /result/STAR-<code> for a non-approved row; there is no View button (no Action column)', () => {
    const { q, el } = render();
    expect(q('pfm-row-title').getAttribute('href')).toBe('/result/STAR-1234?from=pfm-monitor');
    expect(el.querySelector('[data-testid="pfm-row-view"]')).toBeNull();
    expect(el.querySelectorAll('td')).toHaveLength(9);
  });

  it('Code cell shows platform and number; Indicator cell shows type', () => {
    const { q } = render();
    expect(q('pfm-row-code-platform').textContent?.trim()).toBe('STAR');
    expect(q('pfm-row-code-number').textContent?.trim()).toBe('1234');
    expect(q('pfm-row-code').textContent).toMatch(/STAR\s*1234/);
    expect(q('pfm-row-indicator').textContent?.trim()).toBe('Innovation development');
    expect(render({ official_code: 7 }).q('pfm-row-code-number').textContent?.trim()).toBe('007');
  });

  it('title follows the Results Center rule: inner div clamps 3 lines (2 on xl), the link is not clamped, full text in title, underline only on hover/focus', () => {
    const long = 'Long title '.repeat(60).trim();
    const { q } = render({ title: long });
    const t = q('pfm-row-title');
    const inner = t.querySelector('div') as HTMLElement;
    expect(inner.classList).toContain('overflow-hidden');
    expect(inner.classList).toContain('line-clamp-3');
    expect(inner.classList).toContain('xl:line-clamp-2');
    expect(inner.textContent?.trim()).toBe(long);
    expect(t.classList).not.toContain('line-clamp-3');
    expect(t.classList).toContain('block');
    expect(t.classList).toContain('w-full');
    expect(t.getAttribute('title')).toBe(long);
    expect(t.classList).toContain('no-underline');
    expect(t.className).toContain('hover:underline');
    expect(t.className).toContain('focus-visible:underline');
  });

  it('Creator cell shows the creator name, or a dash when there is none', () => {
    expect(render().q('pfm-row-creator').textContent?.trim()).toBe('Ana Perez');
    expect(render({ creator: null }).q('pfm-row-creator').textContent?.trim()).toBe('-');
  });

  it('Science Programs cell renders one custom-tag per program, code as text, primary first with the name + primary tooltip (HITL 22)', () => {
    const { q, tipOf, sr } = render();
    const tags = Array.from(q('pfm-row-sp').querySelectorAll('[data-testid="pfm-row-sp-tag"]')) as HTMLElement[];
    expect(tags.length).toBe(2);
    expect(tags.map(t => t.querySelector('app-custom-tag span.font-semibold')?.textContent?.trim())).toEqual(['SP01', 'SP09']);
    const tips = tags.map(t => tipOf(t));
    expect(tips).toEqual(['Breeding — primary', 'Climate Action']);
    expect(tags[0].getAttribute('data-primary')).toBe('true');
    expect(tags[1].getAttribute('data-primary')).toBe('false');
    // Primary is marked with a star (as in Alliance alignment), not a double border.
    // The star sits inside the tag, after the code.
    expect(tags[0].querySelector('app-custom-tag [data-testid="custom-tag-trailing-icon"].pi-star-fill')).not.toBeNull();
    expect(tags[1].querySelector('[data-testid="custom-tag-trailing-icon"]')).toBeNull();
    expect(tags[0].classList).not.toContain('ring-2');
    // every SP pill hugs its code (no fixed 45px label width)
    tags.forEach(t => expect(t.querySelector('app-custom-tag span')!.className).not.toContain('min-w-[45px]'));
    expect(sr(q('pfm-row-sp'))).toEqual(['SP01 Breeding, primary', 'SP09 Climate Action']);
    expect(q('pfm-row-sp').querySelector('[data-testid="pfm-row-sp-line"]')).toBeNull();
  });

  it('SP tag text uses the neutral token (contrast); the DB colour only drives border and icon', () => {
    const { q, tagsIn } = render();
    const [primary, other] = tagsIn(q('pfm-row-sp'));
    expect(primary.statusColor).toBe('var(--ac-pfm-neutral-fg)');
    expect(primary.statusBorder).toBe('#112233');
    expect(primary.iconColor).toBe('#112233');
    expect(other.statusColor).toBe('var(--ac-pfm-neutral-fg)');
    expect(other.statusBorder).toBe('var(--ac-pfm-neutral-fg)');
  });

  it('Science Programs cell shows a muted dash when there are no programs', () => {
    const { q } = render({ science_programs: [] });
    const sp = q('pfm-row-sp');
    expect(sp.textContent?.trim()).toBe('—');
    expect(sp.querySelector('app-custom-tag')).toBeNull();
  });

  it('mapping cell is an app-custom-tag with the note as tooltip and semantic tokens, nothing below it (HITL 22)', () => {
    const { q, tipOf, tagsIn, sr } = render();
    const cell = q('pfm-row-mapping');
    const tag = cell.querySelector('app-custom-tag') as HTMLElement;
    expect(tag.textContent?.trim()).toBe('Pending');
    expect(tipOf(cell)).toBe('Budget shares missing');
    expect(sr(cell)).toEqual(['Budget shares missing']);
    expect(cell.querySelector('[data-testid="pfm-row-mapping-note"]')).toBeNull();
    expect(cell.querySelectorAll('p').length).toBe(0);
    // jsdom drops var() colours from the CSSOM, so assert the inputs the tag receives.
    const [t] = tagsIn(cell);
    expect(t.statusColor).toBe('var(--ac-status-mapping-pending)');
    expect(t.statusBorder).toBe('var(--ac-status-mapping-pending)');
  });

  it('approved (6) with snapshot years opens the latest snapshot version', () => {
    const { q } = render({ star_status_id: 6, star_label: 'Approved', snapshot_years: [2023, 2025, 2024] });
    const expected = '/result/STAR-1234/general-information?version=2025&from=pfm-monitor';
    expect(q('pfm-row-title').getAttribute('href')).toBe(expected);
  });

  it('approved without snapshot years has no version', () => {
    const { q } = render({ star_status_id: 6, star_label: 'Approved', snapshot_years: [] });
    expect(q('pfm-row-title').getAttribute('href')).toBe('/result/STAR-1234?from=pfm-monitor');
  });

  it('the title link is present on out-of-scope and mapping-pending rows', () => {
    expect(render({ mapping_state: 'No SP contribution', sp_line: 'Not reported to PRMS' }).q('pfm-row-title')).not.toBeNull();
    expect(render({ mapping_state: 'Pending' }).q('pfm-row-title')).not.toBeNull();
  });

  it('renders server values as received and no other action', () => {
    const { el, q } = render();
    expect(q('pfm-row-updated').textContent?.trim()).toBe('03 Oct, 14:05');
    expect(q('pfm-row-pi-line')).toBeNull();
    expect(q('pfm-row-mapping-note')).toBeNull();
    expect(q('pfm-row-meta')).toBeNull();
    expect(el.querySelectorAll('a').length).toBe(1); // the title is the only link
    expect(el.querySelector('button')).toBeNull();
    expect(el.textContent).not.toMatch(/Sync|Request approval|Complete mapping/);
  });

  it('PRMS "Not sent" keeps the dash and carries the hint as tooltip and accessible name (HITL 22, R-PFM-004)', () => {
    const { q, tipOf } = render();
    const dash = q('pfm-badge-not-sent');
    expect(dash.getAttribute('role')).toBe('img');
    expect(dash.getAttribute('aria-label')).toBe('Not sent: Not synced to PRMS yet');
    expect(tipOf(q('pfm-row-prms'))).toBe('Not synced to PRMS yet');
    expect(q('pfm-row-prms').querySelector('app-custom-tag')).toBeNull();
  });

  it('PRMS Rejected is an app-custom-tag in the danger tokens with the hint as tooltip and sr-only text (HITL 22)', () => {
    const { q, tipOf, tagsIn, sr } = render({ prms_status: 'Rejected', prms_hint: 'Fix the Theory of Change in PRMS' });
    const cell = q('pfm-row-prms');
    expect((cell.querySelector('app-custom-tag') as HTMLElement).textContent).toContain('Rejected');
    expect(tipOf(cell)).toBe('Fix the Theory of Change in PRMS');
    expect(sr(cell)).toEqual(['Fix the Theory of Change in PRMS']);
    expect(tagsIn(cell)[0].statusColor).toBe('var(--ac-status-prms-rejected)');
  });

  // One colour per status across screens: the monitor PRMS cell must match the result
  // sidebar PRMS sync pill (SYNC_TAG_COLOR) for the same status.
  it.each([
    ['Pending Review', 'warning'],
    ['Approved', 'success'],
    ['Rejected', 'danger']
  ] as const)('PRMS %s uses the same colour as the result sidebar PRMS sync pill', (status, tone) => {
    const { q, tagsIn } = render({ prms_status: status });
    const [t] = tagsIn(q('pfm-row-prms'));
    expect(t.statusColor).toBe(SYNC_TAG_COLOR[tone]);
    expect(t.statusBorder).toBe(SYNC_TAG_COLOR[tone]);
  });

  it.each([
    ['Pending', MAPPING_STATUS_COLOR.Pending],
    ['Complete', MAPPING_STATUS_COLOR.Complete],
    ['No SP contribution', MAPPING_STATUS_COLOR['No SP contribution']]
  ] as const)('mapping %s uses its shared status colour', (state, color) => {
    const { q, tagsIn } = render({ mapping_state: state });
    expect(tagsIn(q('pfm-row-mapping'))[0].statusColor).toBe(color);
  });

  it('Complete is a different colour from Pending and from No SP contribution', () => {
    const colors = new Set([MAPPING_STATUS_COLOR.Complete, MAPPING_STATUS_COLOR.Pending, MAPPING_STATUS_COLOR['No SP contribution']]);
    expect(colors.size).toBe(3);
  });

  it('clicking the title opens no dialog or drawer', () => {
    const { el, q } = render();
    q('pfm-row-title').addEventListener('click', e => e.preventDefault());
    q('pfm-row-title').click();
    expect(el.querySelector('[role="dialog"], p-dialog, p-drawer, p-sidebar, dialog')).toBeNull();
  });
});
