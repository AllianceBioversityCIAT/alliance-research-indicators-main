import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { PfmResultRow } from '../../pfm.interfaces';
import { PfmResultRowComponent } from './pfm-result-row.component';

const BASE: PfmResultRow = {
  result_code: 'STAR-1234',
  platform_code: 'STAR',
  official_code: 1234,
  report_year: 2025,
  snapshot_years: [],
  title: 'Alpha result',
  type: 'Innovation development',
  star_label: 'Submitted',
  star_status_id: 2,
  pi_line: 'Awaiting PI approval',
  mapping_state: 'Incomplete',
  mapping_note: 'Budget shares missing',
  sp_line: 'SP01 (primary)',
  primary_sp: { code: 'SP01', name: 'Breeding', color: '#112233' },
  contributing: [],
  prms_status: 'Not sent',
  prms_hint: 'Not synced to PRMS yet',
  updated_at: '03 Oct, 14:05'
};

// Real RouterLink with provideRouter([]): the href is generated by Angular, not mocked.
function render(over: Partial<PfmResultRow> = {}) {
  TestBed.resetTestingModule();
  TestBed.configureTestingModule({ imports: [PfmResultRowComponent], providers: [provideRouter([])] });
  const fixture = TestBed.createComponent(PfmResultRowComponent);
  fixture.componentRef.setInput('row', { ...BASE, ...over });
  fixture.detectChanges();
  const el = fixture.nativeElement as HTMLElement;
  return { el, q: (id: string) => el.querySelector(`[data-testid="${id}"]`) as HTMLElement };
}

describe('PfmResultRowComponent', () => {
  it('View href is /result/STAR-<code> for a non-approved row, and the title links to the same place', () => {
    const { q } = render();
    expect(q('pfm-row-view').getAttribute('href')).toBe('/result/STAR-1234?from=pfm-monitor');
    expect(q('pfm-row-title').getAttribute('href')).toBe('/result/STAR-1234?from=pfm-monitor');
  });

  it('Code cell shows platform and number; Indicator cell shows type', () => {
    const { q } = render();
    expect(q('pfm-row-code-platform').textContent?.trim()).toBe('STAR');
    expect(q('pfm-row-code-number').textContent?.trim()).toBe('1234');
    expect(q('pfm-row-code').textContent).toMatch(/STAR\s*1234/);
    expect(q('pfm-row-indicator').textContent?.trim()).toBe('Innovation development');
    expect(render({ official_code: 7 }).q('pfm-row-code-number').textContent?.trim()).toBe('007');
  });

  it('title is clamped to 3 lines, carries the full text as title, and is not underlined at rest', () => {
    const long = 'Long title '.repeat(60).trim();
    const { q } = render({ title: long });
    const t = q('pfm-row-title');
    expect(t.classList).toContain('line-clamp-3');
    expect(t.getAttribute('title')).toBe(long);
    expect(t.classList).toContain('no-underline');
  });

  it('approved (6) with snapshot years opens the latest snapshot version', () => {
    const { q } = render({ star_status_id: 6, star_label: 'Approved', snapshot_years: [2023, 2025, 2024] });
    const expected = '/result/STAR-1234/general-information?version=2025&from=pfm-monitor';
    expect(q('pfm-row-view').getAttribute('href')).toBe(expected);
    expect(q('pfm-row-title').getAttribute('href')).toBe(expected);
  });

  it('approved without snapshot years has no version', () => {
    const { q } = render({ star_status_id: 6, star_label: 'Approved', snapshot_years: [] });
    expect(q('pfm-row-view').getAttribute('href')).toBe('/result/STAR-1234?from=pfm-monitor');
  });

  it('View is present on out-of-scope and mapping-incomplete rows', () => {
    expect(render({ mapping_state: 'No SP contribution', sp_line: 'Not reported to PRMS' }).q('pfm-row-view')).not.toBeNull();
    expect(render({ mapping_state: 'Incomplete' }).q('pfm-row-view')).not.toBeNull();
  });

  it('renders server values as received and no other action', () => {
    const { el, q } = render();
    expect(q('pfm-row-updated').textContent?.trim()).toBe('03 Oct, 14:05');
    expect(q('pfm-row-pi-line').textContent?.trim()).toBe('Awaiting PI approval');
    expect(q('pfm-row-mapping-note').textContent?.trim()).toBe('Budget shares missing');
    expect(q('pfm-row-meta')).toBeNull();
    expect(el.querySelectorAll('a').length).toBe(2);
    expect(el.querySelector('button')).toBeNull();
    expect(el.textContent).not.toMatch(/Sync|Request approval|Complete mapping/);
  });

  it('PRMS "Not sent" shows an accessible dash with a tooltip; Rejected carries the hint as tooltip', () => {
    const dash = render().q('pfm-badge-not-sent');
    expect(dash.getAttribute('aria-label')).toBe('Not sent');
    // Effective tooltip = the dash's own title, else the nearest titled ancestor (the PRMS cell, bound to prms_hint).
    expect(dash.closest('[title]')?.getAttribute('title')).toBe('Not synced to PRMS yet');
    const rej = render({ prms_status: 'Rejected', prms_hint: 'PRMS: Rejected — fix the Theory of Change' });
    expect(rej.q('pfm-row-prms').getAttribute('title')).toBe('PRMS: Rejected — fix the Theory of Change');
    expect(rej.q('pfm-row-prms').textContent?.trim()).toBe('Rejected');
  });

  it('click on View opens no dialog or drawer', () => {
    const { el, q } = render();
    q('pfm-row-view').addEventListener('click', e => e.preventDefault());
    q('pfm-row-view').click();
    expect(el.querySelector('[role="dialog"], p-dialog, p-drawer, p-sidebar, dialog')).toBeNull();
  });
});
